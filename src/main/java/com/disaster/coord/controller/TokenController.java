package com.disaster.coord.controller;

import com.disaster.coord.dto.ApiResponse;
import com.disaster.coord.dto.SaveTokenRequest;
import com.disaster.coord.entity.User;
import com.disaster.coord.repository.UserRepository;
import com.disaster.coord.service.FcmNotificationService;
import lombok.RequiredArgsConstructor;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.util.HashMap;
import java.util.Map;

/**
 * Backend endpoint for Android App FCM Token and Location Registration.
 */
@RestController
@RequestMapping("/api")
@RequiredArgsConstructor
@CrossOrigin(origins = "*")
public class TokenController {

    private static final Logger log = LoggerFactory.getLogger(TokenController.class);
    private final UserRepository userRepository;
    private final FcmNotificationService fcmNotificationService;
    private final com.disaster.coord.service.FirebasePushSender firebasePushSender;

    @PostMapping({"/save-token", "/save-device-token", "/users/device-token"})
    public ResponseEntity<ApiResponse<Map<String, Object>>> saveToken(@RequestBody SaveTokenRequest request) {
        log.info("Received save-token request: userId={}, lat={}, lng={}, fcmToken={}...",
                request.getUserId(), request.getLatitude(), request.getLongitude(),
                request.getFcmToken() != null ? request.getFcmToken().substring(0, Math.min(12, request.getFcmToken().length())) : "null");

        if (request.getFcmToken() == null || request.getFcmToken().isBlank()) {
            return ResponseEntity.badRequest()
                    .body(ApiResponse.error("fcmToken cannot be null or empty"));
        }

        String token = request.getFcmToken().trim();
        if (token.length() < 100 || token.startsWith("fcm_") || token.startsWith("mock_") || token.startsWith("test_")) {
            log.warn("Rejected invalid FCM token format: '{}' (length={})", token, token.length());
            return ResponseEntity.badRequest()
                    .body(ApiResponse.error("Invalid FCM token format: FCM tokens must be generated by Firebase SDK (minimum 100 characters)."));
        }

        Long uid = null;
        if (request.getUserId() != null && !request.getUserId().isBlank()) {
            try {
                uid = Long.parseLong(request.getUserId());
            } catch (NumberFormatException e) {
                log.warn("Invalid userId format: {}", request.getUserId());
            }
        }

        Double lat = null;
        Double lng = null;
        if (request.getLatitude() != null && !request.getLatitude().isBlank()) {
            try {
                lat = Double.parseDouble(request.getLatitude());
            } catch (NumberFormatException ignored) {}
        }
        if (request.getLongitude() != null && !request.getLongitude().isBlank()) {
            try {
                lng = Double.parseDouble(request.getLongitude());
            } catch (NumberFormatException ignored) {}
        }

        if (uid != null) {
            final Long finalUid = uid;
            final Double finalLat = lat;
            final Double finalLng = lng;
            userRepository.findById(finalUid).ifPresent(user -> {
                user.setFcmToken(request.getFcmToken());
                if (finalLat != null) user.setHomeLat(finalLat);
                if (finalLng != null) user.setHomeLng(finalLng);
                userRepository.save(user);
                log.info("Updated User #{} FCM token and home location: ({}, {})", finalUid, finalLat, finalLng);
            });
        }

        // Trigger immediate test push notification ("Hi - Notifications working")
        boolean testPushSent = false;
        try {
            if (firebasePushSender != null) {
                testPushSent = firebasePushSender.sendWelcomeNotification(request.getFcmToken());
            }
            com.disaster.coord.dto.FcmNotificationPayload testPayload = com.disaster.coord.dto.FcmNotificationPayload.builder()
                    .fcmToken(request.getFcmToken())
                    .title("Hi - Notifications working")
                    .body("Your device is registered for emergency disaster alerts.")
                    .disasterType("TEST_ALERT")
                    .address(lat != null && lng != null ? String.format("(%.4f, %.4f)", lat, lng) : "Registered Location")
                    .distanceKm(0.0)
                    .customData(Map.of("type", "WELCOME_TEST", "clickAction", "OPEN_DISASTER_ALERT"))
                    .build();
            boolean simResult = fcmNotificationService.sendNotification(testPayload);
            if (!testPushSent) testPushSent = simResult;
        } catch (Exception ex) {
            log.warn("Failed to dispatch test FCM notification: {}", ex.getMessage());
        }

        Map<String, Object> data = new HashMap<>();
        data.put("userId", request.getUserId());
        data.put("fcmToken", request.getFcmToken());
        data.put("latitude", lat);
        data.put("longitude", lng);
        data.put("status", "REGISTERED");
        data.put("testNotificationSent", testPushSent);

        return ResponseEntity.ok(ApiResponse.ok("FCM Token and Location saved successfully", data));
    }
}
